// Writes PrizeVault's creation bytecode to web/vault-bytecode.js so the page can deploy
// the vault from the user's own wallet. Run after `hardhat compile`.
const fs = require("fs");
const path = require("path");

const artifact = require("../artifacts/contracts/PrizeVault.sol/PrizeVault.json");
const out = path.join(__dirname, "..", "web", "vault-bytecode.js");
fs.writeFileSync(out, `// Generated by scripts/export-bytecode.js. Do not edit.\nexport const VAULT_BYTECODE = "${artifact.bytecode}";\n`);
console.log(`Wrote ${out}`);
